export const getBankByShortCodeOrName = (search: string): BankInfo | undefined => {
  if (!search) return undefined;
  const clean = search.trim().toLowerCase();
  return SRI_LANKA_BANKS.find(
    (b) =>
      b.bankName.toLowerCase() === clean ||
      b.shortCode.toLowerCase() === clean ||
      b.bankName.toLowerCase().includes(clean)
  );
};
